export default function Icon({ name, size = 24, color = '#333', style }) {
  if (Platform.OS === 'web') {
    const emoji = emojiMap[name] || emojiMap[name?.replace('-outline', '')] || '•';
    return (
      <Text 
        style={[
          { 
            fontSize: size * 0.85, 
            lineHeight: size * 1.1, 
            textAlign: 'center',
            width: size,
            height: size,
          }, 
          style
        ]}
      >
        {emoji}
      </Text>
    );
  }
  
  return <Ionicons name={name} size={size} color={color} style={style} />;
}

export function TabIcon({ name, size = 24, color = '#333', focused }) {
  if (Platform.OS === 'web') {
    const emoji = emojiMap[name] || emojiMap[name?.replace('-outline', '')] || '•';
    return (
      <Text 
        style={{ 
          fontSize: size * 0.85, 
          opacity: focused ? 1 : 0.5,
          textAlign: 'center',
        }}
      >
        {emoji}
      </Text>
    );
  }
  
  return <Ionicons name={name} size={size} color={color} />;
}
